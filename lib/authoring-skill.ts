    'jq \'.idea | {updatedAt}\' idea-draft.json > publish-idea.json',
    'curl --fail-with-body -H "Authorization: Bearer $LWR_TOKEN" -H "Content-Type: application/json" --data-binary @publish-idea.json "$LWR_URL/api/admin/project-ideas/$IDEA_SLUG/publish"',
